export interface HilaResult { found: string[]; notes: string[]; unknown: string[]; est?: { kcal: number; p: number; c: number; f: number } }

// מילים "שקופות" — לא מזון בפני עצמו, לא נספרות כ"לא זוהה"
const IGNORE = ['מים', 'כוס', 'בקבוק', 'ללא', 'בלי', 'סוכר', 'מלח', 'שמן', 'בבוקר', 'בערב', 'בצהריים', 'קופסא', 'קופסה', 'גר', 'גרם', 'חצי', 'שקית', 'צלחת', 'כף', 'כפית', 'מנה', 'קטן', 'גדול'];

export function hilaReview(text: string, photoCount = 0, waterMl = 0, waterGoal = 1500): HilaResult {
  const t = text || '';
  const found: string[] = [];
  const notes: string[] = [];
  const unknown: string[] = [];

  if (t.trim().length < 15 && photoCount === 0) {
    return { found, notes: ['רשימה קצרה מדי בשביל להגיב ברצינות — פרט קצת יותר, או צלם.'], unknown };
  }

  // פירוק לשורות/פריטים — מה שלא מזוהה נאמר בפירוש
  const segments = t.split(/[\n,.·;]+/).map(s => s.trim()).filter(s => s.length > 1);
  for (const seg of segments) {
    const matched = CATS.some(c => c.keys.some(k => seg.includes(k)));
    if (!matched) {
      const stripped = seg.split(/\s+/).filter(w => !IGNORE.some(ig => w.includes(ig)) && !/^\d+['"]?$/.test(w)).join(' ');
      if (stripped.length > 2) unknown.push(seg.length > 28 ? seg.slice(0, 28) + '…' : seg);
    }
  }

  const hits = CATS.filter(c => c.keys.some(k => t.includes(k)));
  hits.forEach(c => found.push(c.label));

  // חלבון — התמונה הגדולה קודם
  const proteinN = hits.filter(c => c.protein).length;
  if (proteinN >= 3) notes.push('חלבון ממספר מקורות — בדיוק מה שצריך בחיטוב. 💪');
  else if (proteinN > 0) notes.push(`זיהיתי ${proteinN === 1 ? 'מקור חלבון אחד' : proteinN + ' מקורות חלבון'}. היעד ~130-140 גר' ביום — כנראה צריך עוד: יוגורט פרו, גבינה לבנה או ביצה.`);
  else if (t.trim().length >= 15) notes.push('לא זיהיתי מקור חלבון. בגירעון קלורי בלי חלבון הגוף שורף שריר — תוסיף לארוחה הבאה.');

  // מים — נלקח אוטומטית מהמונה בדשבורד, לא צריך לכתוב (שני בסדר העדיפויות, אחרי חלבון)
  if (waterMl >= waterGoal) notes.push(`מים: ${waterMl} מ"ל — עמדת ביעד היום. 💧 בדיוק מה שהגאוט צריך.`);
  else if (waterMl > 0) notes.push(`מים: ${waterMl} מ"ל מתוך ${waterGoal} (מהמונה בדשבורד). עוד ${Math.ceil((waterGoal - waterMl) / 250)} כוסות ואתה שם.`);
  else notes.push('לא נרשמו מים היום במונה שבדשבורד. עם גאוט זה החוק הכי חשוב — כוס אחת עכשיו, וסמן.');

  // הערות פר קטגוריה
  hits.filter(c => c.note).forEach(c => notes.push(c.note!));

  if (['צום', 'לא אכלתי', 'דילגתי'].some(k => t.includes(k)))
    notes.push('דילוג על ארוחות בגירעון = סיכון גאוט. עדיף קטן ומסודר מכלום.');

  if (photoCount > 0)
    notes.push(`יש ${photoCount === 1 ? 'תמונה אחת' : photoCount + ' תמונות'} ביומן — לחץ "🔍 ניתוח הילה" מתחת לתמונה ואסתכל עליה באמת (דורש חיבור לענן, בטאב הצוות).`);

  // הערכת מאקרו גסה — מנה טיפוסית לכל קטגוריה שזוהתה
  const withMacro = hits.filter(c => c.macro);
  let est;
  if (withMacro.length > 0) {
    est = withMacro.reduce((a, c) => ({ kcal: a.kcal + c.macro![0], p: a.p + c.macro![1], c: a.c + c.macro![2], f: a.f + c.macro![3] }), { kcal: 0, p: 0, c: 0, f: 0 });
  }

  return { found, notes: notes.slice(0, 5), unknown: unknown.slice(0, 4), est };
}
