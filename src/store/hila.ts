// הילה — תגובה מיידית ליומן האוכל. מנוע כללים מקומי (בלי AI):
// מזהה מילות מפתח ומגיב לפי הפרופיל של אבי: חיטוב, גאוט (אלופורינול), יעד חלבון ~130-140 גר'.
// הסקירה המעמיקה נשארת שבועית / בצ'אט.

export function hilaReview(text: string): string[] {
  const t = text || '';
  const out: string[] = [];
  const has = (...ws: string[]) => ws.some(w => t.includes(w));

  const proteinWords = ['ביצ', 'טונה', 'עוף', 'הודו', 'גבינ', 'יוגורט', 'קוטג', 'בשר', 'דג ', 'סלמון', 'טופו', 'עדשים', 'שעועית'];
  const proteinCount = proteinWords.filter(w => t.includes(w)).length;

  if (t.trim().length < 15) {
    out.push('רשימה קצרה מדי בשביל להגיב ברצינות — פרט קצת יותר, או צלם.');
    return out;
  }

  if (proteinCount >= 3) out.push('חלבון במספר ארוחות — בדיוק מה שצריך בחיטוב. 💪');
  else if (proteinCount >= 1) out.push(`זיהיתי ${proteinCount === 1 ? 'מקור חלבון אחד' : proteinCount + ' מקורות חלבון'}. היעד שלך ~130-140 גר' ביום — הוסף יוגורט פרו / גבינה לבנה / ביצה.`);
  else out.push('לא זיהיתי מקור חלבון. בגירעון קלורי בלי חלבון הגוף שורף שריר — תוסיף חלבון לארוחה הבאה.');

  if (has('טונה')) out.push('טונה = פורינים. עם גאוט: עד 2-3 קופסאות בשבוע, תמיד עם כוס מים. ביצים וגבינות — חלבון בטוח יותר.');
  if (has('בירה', 'אלכוהול', 'וודקה', 'ויסקי', 'ערק')) out.push('ד"ר ארז מתערב: אלכוהול הוא טריגר גאוט מספר אחת, בירה בראש הרשימה. מינימום, ומים לידו.');
  if (has('במבה')) out.push('במבה בתקציב — עד 50-80 גר\' ליום, כמו שסיכמנו. ספרת אותה? מצוין.');
  if (has('עוגה', 'שוקולד', 'ממתק', 'גלידה', 'בורקס', 'קרואסון')) out.push('מתוק/מאפה — לא אסון, רק שיהיה מתוכנן ולא מתוך לחץ.');
  if (has('סלט', 'ירקות')) out.push('ירקות — עבודה נקייה.');
  if (has('צום', 'לא אכלתי', 'דילגתי')) out.push('דילוג על ארוחות בגירעון = סיכון גאוט. עדיף קטן ומסודר מכלום.');

  return out.slice(0, 3);
}
