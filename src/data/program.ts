// כל תרגיל: גרסת חדר כושר + גרסת בית שקולות. בטיחות: גב (בלט+ליסתזיס), ברכיים (אין מיניסקוס ימין, קרע שמאל), גאוט.

export type Loc = 'home' | 'gym';

// פרמטר מותאם לתרגיל מעבר למשקל (למשל גובה קופסה/מדרגה) — לתיעוד ולניתוח תנועה בעתיד
export interface ExParam {
  key: string;             // מזהה יציב לשמירה
  label: string;           // תווית בעברית
  unit?: string;           // יחידה (ס"מ וכו')
  step?: number;           // צעד הכפתורים ± (ברירת מחדל 1)
  def?: number;            // ערך התחלתי אם אין היסטוריה
}

// גרסת מיקום — יכולה לשנות גם מבנה (לא רק שם/הערה), כדי שחדר ובית יהיו תרגילים שונים באמת
export interface ExVariant { name?: string; note?: string; target?: string; setsDefault?: number; repsDefault?: number; timeBased?: boolean; weighted?: boolean; restDefault?: number }

// ---------------------------------------------------------------------------
// שלבים. תרגיל שאבי לא מצליח לבצע אינו תרגיל — הוא שורה ביומן שלא זזה.
// Negative Muscle-Up עמד על 2 חזרות שבעה אימונים מתוך שבעה מול יעד של 3×5,
// ו-Lever על 2 שניות מול יעד של 3-5 דקות. בשני המקרים היעד הכתוב לא נגע
// במציאות, ולא היה שום מסלול שמוביל אליו — רק טקסט ב-harder.
//
// שלב הוא תרגיל שלם בפני עצמו: שם, יעד, ומבנה סטים משלו. מה שהופך אותו
// לשלב ולא לתרגיל אחר הוא ה-gate: מספר מדיד שקובע מתי עוברים הלאה. בלעדיו
// "סולם" הוא רשימת מילים, וזה מה שהיה ל-Lever מההתחלה.
//
// השלב הנוכחי נשמר ב-DB (stageByEx) ולא בקוד, כדי שאבי יקדם אותו באפליקציה
// ולא יחכה לקומיט. שינוי שלב משנה את שם התרגיל, ולכן progress.ts מסווג אותו
// 'variant' ולא משווה בין שלבים — 20 שניות בשלב 1 אינן נסיגה מ-2 שניות בשלב 3.
export interface ExStage {
  name: string;            // שם השלב — מחליף את שם התרגיל בתצוגה וביומן
  target: string;
  gate: string;            // מה בדיוק צריך כדי לעבור הלאה. מספר, לא הרגשה
  setsDefault: number;
  repsDefault: number;     // שניות כש-timeBased
  timeBased?: boolean;
  note?: string;           // איך מבצעים את השלב הזה
  tips?: string[];         // קול הצוות לשלב. חובה כשיש שלבים: טיפ של התרגיל
  //   המלא מטעה בשלב מוקדם ("מרפק שמתכופף זה תרגיל אחר" על Hollow Body).
}

export interface ExerciseDef {
  id: string;
  name: string;            // base Hebrew name
  target: string;          // sets x reps text
  setsDefault: number;
  repsDefault: number;
  weighted?: boolean;      // show weight field
  timeBased?: boolean;
  restDefault?: number;    // ברירת-מחדל זמן מנוחה לתרגיל (שניות) — נפילה כשאין הגדרה פר-תרגיל של אבי
  gym?: ExVariant;
  home?: ExVariant;
  note?: string;           // shared note
  area?: string;           // body area for pain correlation
  params?: ExParam[];      // פרמטרים מותאמים (גובה קופסה/מדרגה וכו') — סעיף 5
  tips?: string[];         // טיפים משתנים בקול הצוות — מוצג אחד לכל אימון, מתחלף (סעיף 5)
  harder?: string;         // איך מקשים בלי להוסיף עומס — לתרגילי שיקום, שבהם "קל מדי" לא פותרים במשקל
  cues?: string[];         // דגשים שמוצגים תמיד, לא מתחלפים — לתרגיל שנתקעים בו וצריך אותם מול העיניים
  stages?: ExStage[];      // סולם שלבים — ראו ExStage. השלב הנוכחי ב-db.stageByEx
  tempoSec?: number;       // תרגיל טמפו: שניות לירידה אחת. מפעיל טיימר בצליל נפרד,
  //   כי בלי קצב קבוע אין מה להשוות בין אימונים — אותן חמש חזרות הן 50 שניות או 75.
}

