/** השלב הפעיל, מוגן מפני אינדקס מחוץ לתחום (גיבוי ישן, שלב שנמחק מהקוד) */
export function exStage(ex: ExerciseDef, stage?: number): ExStage | undefined {
  if (!ex.stages?.length) return undefined;
  const i = Math.min(Math.max(stage ?? 0, 0), ex.stages.length - 1);
  return ex.stages[i];
}

export function exName(ex: ExerciseDef, loc: Loc, stage?: number): string {
  const st = exStage(ex, stage);
  if (st) return st.name;
  return (loc === 'home' ? ex.home?.name : ex.gym?.name) || ex.name;
}
export function exNote(ex: ExerciseDef, loc: Loc, stage?: number): string | undefined {
  const sg = exStage(ex, stage);
  if (sg) return sg.note;   // הערת השלב מחליפה — הערת הבסיס מתארת תרגיל אחר
  const locNote = loc === 'home' ? ex.home?.note : ex.gym?.note;
  return [ex.note, locNote].filter(Boolean).join(' · ') || undefined;
}

// מבנה אפקטיבי פר-מיקום: הגרסה (חדר/בית) גוברת על הבסיס. מאפשר תרגיל שונה בחדר ובבית.
export function exStruct(ex: ExerciseDef, loc: Loc, stage?: number): { setsDefault: number; repsDefault: number; timeBased?: boolean; weighted?: boolean; restDefault?: number; target: string; tempoSec?: number } {
  const v = loc === 'home' ? ex.home : ex.gym;
  // השלב גובר על גרסת המיקום: שלב הוא תרגיל אחר לגמרי, ולא התאמה של אותו תרגיל
  // לחדר או לבית. timeBased נלקח מהשלב כמו שהוא, גם false — תלייה נמדדת בשניות
  // ו-High Pull בחזרות, באותו סלוט.
  const sg = exStage(ex, stage);
  return {
    tempoSec: (v as { tempoSec?: number } | undefined)?.tempoSec ?? ex.tempoSec,
    setsDefault: sg?.setsDefault ?? v?.setsDefault ?? ex.setsDefault,
    repsDefault: sg?.repsDefault ?? v?.repsDefault ?? ex.repsDefault,
    timeBased: sg ? sg.timeBased : (v?.timeBased ?? ex.timeBased),
    weighted: sg ? false : (v?.weighted ?? ex.weighted),
    restDefault: v?.restDefault ?? ex.restDefault,
    target: sg?.target ?? v?.target ?? ex.target,
  };
}
